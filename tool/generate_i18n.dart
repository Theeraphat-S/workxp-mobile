import 'dart:convert';
import 'dart:io';

void main() {
  final rootDir = Directory.current.path;
  final localsDir = Directory('$rootDir/lib/i18n/locals');
  final outputFile = File('$rootDir/lib/i18n/i18n.dart');

  if (!localsDir.existsSync()) {
    stderr.writeln('Error: Directory not found: ${localsDir.path}');
    exit(1);
  }

  stdout.writeln('Generating i18n from ${localsDir.path}...');

  final featureDirs = localsDir.listSync().whereType<Directory>().toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  final features = <FeatureData>[];
  final supportedLocales = <String>{'en', 'th'};

  for (final dir in featureDirs) {
    final folderName = dir.path.replaceAll(r'\', '/').split('/').last;
    final arbFiles = dir
        .listSync()
        .whereType<File>()
        .where((f) => f.path.endsWith('.arb'))
        .toList();

    final feature = FeatureData(folderName);

    for (final file in arbFiles) {
      final fileName = file.path.replaceAll(r'\', '/').split('/').last;
      final langCode = fileName.replaceAll('.arb', '');
      supportedLocales.add(langCode);

      try {
        final content = file.readAsStringSync();
        final Map<String, dynamic> json = jsonDecode(content);

        for (final entry in json.entries) {
          if (entry.key.startsWith('@')) continue;
          feature.addString(langCode, entry.key, entry.value.toString());
        }
      } catch (e) {
        stderr.writeln('Error reading $fileName in $folderName: $e');
      }
    }

    features.add(feature);
  }

  final buffer = StringBuffer();

  buffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
  buffer.writeln('// Generated by tool/generate_i18n.dart');
  buffer.writeln();
  buffer.writeln("import 'package:flutter/foundation.dart';");
  buffer.writeln("import 'package:flutter/widgets.dart';");
  buffer.writeln();

  // Root I18n class
  buffer.writeln('/// Central WorkXP Internationalization Root');
  buffer.writeln('class I18n {');
  buffer.writeln('  final Locale locale;');
  buffer.writeln();
  buffer.writeln('  I18n(this.locale);');
  buffer.writeln();
  buffer.writeln('  static I18n of(BuildContext context) {');
  buffer.writeln(
    '    return Localizations.of<I18n>(context, I18n) ?? I18n(const Locale(\'en\'));',
  );
  buffer.writeln('  }');
  buffer.writeln();
  buffer.writeln('  static I18n? maybeOf(BuildContext context) {');
  buffer.writeln('    return Localizations.of<I18n>(context, I18n);');
  buffer.writeln('  }');
  buffer.writeln();
  buffer.writeln(
    '  static const LocalizationsDelegate<I18n> delegate = _I18nDelegate();',
  );
  buffer.writeln();
  buffer.writeln('  static const List<Locale> supportedLocales = [');
  final sortedLocales = supportedLocales.toList()..sort();
  for (final loc in sortedLocales) {
    buffer.writeln("    Locale('$loc'),");
  }
  buffer.writeln('  ];');
  buffer.writeln();

  // Feature Getters
  for (final f in features) {
    buffer.writeln(
      '  late final ${f.className} ${f.fieldName} = ${f.className}(locale);',
    );
  }
  buffer.writeln();

  // Dynamic Translate Helper
  buffer.writeln(
    '  /// Dynamic translation lookup across all feature namespaces.',
  );
  buffer.writeln(
    '  String translate(String feature, String key, [Map<String, dynamic>? params]) {',
  );
  buffer.writeln('    switch (feature) {');
  for (final f in features) {
    buffer.writeln("      case '${f.folderName}':");
    if (f.folderName != f.fieldName) {
      buffer.writeln("      case '${f.fieldName}':");
    }
    buffer.writeln('        return ${f.fieldName}.lookup(key, params);');
  }
  buffer.writeln('      default:');
  buffer.writeln('        return key;');
  buffer.writeln('    }');
  buffer.writeln('  }');
  buffer.writeln('}');
  buffer.writeln();

  // Feature Subclasses
  for (final f in features) {
    buffer.writeln('class ${f.className} {');
    buffer.writeln('  final Locale locale;');
    buffer.writeln('  const ${f.className}(this.locale);');
    buffer.writeln();
    buffer.writeln(
      '  static const Map<String, Map<String, String>> _values = {',
    );
    for (final loc in sortedLocales) {
      buffer.writeln("    '$loc': {");
      final entries = f.stringsFor(loc);
      for (final entry in entries.entries) {
        final safeVal = _escapeDartString(entry.value);
        buffer.writeln("      '${entry.key}': '$safeVal',");
      }
      buffer.writeln('    },');
    }
    buffer.writeln('  };');
    buffer.writeln();

    // lookup method
    buffer.writeln(
      '  String lookup(String key, [Map<String, dynamic>? params]) {',
    );
    buffer.writeln('    final lang = locale.languageCode;');
    buffer.writeln(
      "    var text = _values[lang]?[key] ?? _values['en']?[key] ?? key;",
    );
    buffer.writeln('    if (params != null) {');
    buffer.writeln('      params.forEach((k, v) {');
    buffer.writeln(r"        text = text.replaceAll('{$k}', v.toString());");
    buffer.writeln('      });');
    buffer.writeln('    }');
    buffer.writeln('    return text;');
    buffer.writeln('  }');
    buffer.writeln();

    // Typed getters / methods
    final allKeys = f.allKeys.toList()..sort();
    for (final key in allKeys) {
      final placeholders = f.getPlaceholders(key);
      if (placeholders.isEmpty) {
        buffer.writeln("  String get $key => lookup('$key');");
      } else {
        final paramsDecl = placeholders.map((p) => 'Object $p').join(', ');
        final paramsMap = '{${placeholders.map((p) => "'$p': $p").join(', ')}}';
        buffer.writeln(
          "  String $key($paramsDecl) => lookup('$key', $paramsMap);",
        );
      }
    }

    buffer.writeln('}');
    buffer.writeln();
  }

  // Localizations Delegate
  buffer.writeln('class _I18nDelegate extends LocalizationsDelegate<I18n> {');
  buffer.writeln('  const _I18nDelegate();');
  buffer.writeln();
  buffer.writeln('  @override');
  final supportedList = sortedLocales.map((l) => "'$l'").join(', ');
  buffer.writeln(
    '  bool isSupported(Locale locale) => [$supportedList].contains(locale.languageCode);',
  );
  buffer.writeln();
  buffer.writeln('  @override');
  buffer.writeln(
    '  Future<I18n> load(Locale locale) => SynchronousFuture<I18n>(I18n(locale));',
  );
  buffer.writeln();
  buffer.writeln('  @override');
  buffer.writeln('  bool shouldReload(_I18nDelegate old) => false;');
  buffer.writeln('}');

  outputFile.parent.createSync(recursive: true);
  outputFile.writeAsStringSync(buffer.toString());

  stdout.writeln(
    'Successfully generated ${outputFile.path} with ${features.length} namespaces.',
  );
}

String _escapeDartString(String value) {
  return value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r');
}

class FeatureData {
  final String folderName;
  final Map<String, Map<String, String>> translations = {};

  FeatureData(this.folderName);

  String get fieldName => _toCamelCase(folderName);
  String get className => '${_toPascalCase(folderName)}I18n';

  void addString(String locale, String key, String value) {
    translations.putIfAbsent(locale, () => {})[key] = value;
  }

  Map<String, String> stringsFor(String locale) => translations[locale] ?? {};

  Set<String> get allKeys {
    final keys = <String>{};
    for (final m in translations.values) {
      keys.addAll(m.keys);
    }
    return keys;
  }

  List<String> getPlaceholders(String key) {
    // Look for placeholders in any available locale for this key
    final regex = RegExp(r'\{([a-zA-Z0-9_]+)\}');
    final placeholders = <String>{};

    for (final locMap in translations.values) {
      final val = locMap[key];
      if (val != null) {
        for (final match in regex.allMatches(val)) {
          final p = match.group(1);
          if (p != null) placeholders.add(p);
        }
      }
    }

    return placeholders.toList();
  }

  static String _toCamelCase(String text) {
    final parts = text.split('_');
    if (parts.length <= 1) return text;
    return parts.first +
        parts
            .skip(1)
            .map((p) => p.isEmpty ? '' : p[0].toUpperCase() + p.substring(1))
            .join();
  }

  static String _toPascalCase(String text) {
    final parts = text.split('_');
    return parts
        .map((p) => p.isEmpty ? '' : p[0].toUpperCase() + p.substring(1))
        .join();
  }
}
